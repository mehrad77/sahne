// Writes two files from the set kit (src/set/):
// - src/set/families.gen.ts: which family each set piece and prop is in, so an app can load only the
//   families its places use (`loadSet`) without loading the others to find out;
// - SET.md: the catalogue of every set piece and prop: its family, what it is, the params it reads
//   with their values and defaults, the place states it answers to, its named variants, and the places
//   that use it. All but the places come from each generator's `meta` (PieceDef.meta; test/meta.test.ts
//   holds the meta to what the drawing reads). Its Credits section is src/set/drawn/CREDITS.json (written by
//   drawing/promote.ts, which runs this after it promotes an item).
//
//   node packages/sahne-kit/set/build.ts           write them
//   node packages/sahne-kit/set/build.ts --check   fail when either is stale (the kit's tests run this)

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import type { PieceDef, ParamSpec } from "sahne";
import { FAMILY_MODULES } from "../src/set/all.ts";
import { SAMPLES } from "../../sahne-story/paths.ts";

/** The sample places (never $SAHNE_CONTENT, so SET.md is the same wherever it is built). */
const PLACES = new URL("places/", SAMPLES);

const OUT = new URL("../src/set/families.gen.ts", import.meta.url);
const MD = new URL("../SET.md", import.meta.url);
const SRC = new URL("../src/set/", import.meta.url);
const PLAN = new URL("plan.json", import.meta.url);
const CREDITS = new URL("../src/set/drawn/CREDITS.json", import.meta.url);

/** A generator or variants still to draw (`set/plan.json`). */
export interface Planned { family: string; as: "set" | "prop" | "both"; step: string; about: string; variants: string[]; built?: true }
export const plan = (): Record<string, Planned> => JSON.parse(readFileSync(PLAN, "utf8")).generators;

export function render(): string {
  const map = (kind: "set" | "props") => {
    const rows = Object.entries(FAMILY_MODULES).flatMap(([name, f]) => Object.keys(f[kind]).map(id => [id, name]));
    rows.sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
    return rows.map(([id, name]) => `  ${/^[a-z_][a-z0-9_]*$/.test(id) ? id : JSON.stringify(id)}: "${name}",`).join("\n");
  };
  return `// Generated by packages/sahne-kit/set/build.ts: do not edit. Which family each id is in.\n\n` +
    `export const SET_FAMILY: Record<string, string> = {\n${map("set")}\n};\n\n` +
    `export const PROP_FAMILY: Record<string, string> = {\n${map("props")}\n};\n`;
}

/** A param for the table: its name, then its values (the default in bold), range or kinds. */
export function paramCell(name: string, spec: ParamSpec): string {
  const d = spec.default, kinds = typeof spec.type === "string" ? [spec.type] : [...spec.type];
  const one = (t: string) => {
    switch (t) {
      case "enum": return (spec.values ?? []).map(v => v === d ? `**${v}**` : v).join(", ");
      case "int": case "num": {
        const range = spec.min !== undefined || spec.max !== undefined ? `${spec.min ?? ""}–${spec.max ?? ""}` : t === "int" ? "whole" : "number";
        return `${range}${d !== undefined && typeof d === "number" ? ` (${d})` : ""}`;
      }
      case "bool": return d === true ? "on/off (on)" : "on/off";
      default: return t;
    }
  };
  return `\`${name}\`: ${kinds.map(one).join(" or ")}`;
}

/** Which sample places use each kit id (pieces and props). */
function usedBy(): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const f of readdirSync(PLACES).filter(f => f.endsWith(".json") && f !== "needs.json").sort()) {
    const doc = JSON.parse(readFileSync(new URL(f, PLACES), "utf8")) as { id: string; pieces?: { kit: string }[]; props?: Record<string, { kit: string }> };
    for (const k of new Set([...(doc.pieces ?? []).map(p => p.kit), ...Object.values(doc.props ?? {}).map(p => p.kit)])) (out[k] ??= []).push(doc.id);
  }
  return out;
}

const cell = (v: string) => v.replace(/[\r\n]+/g, " ").replace(/\|/g, "\\|");

export function renderMd(): string {
  const used = usedBy(), lines = [
    "# The set kit",
    "",
    "Generated by `packages/sahne-kit/set/build.ts` from `src/set/`: do not edit. Every set piece and prop, by family (each family is a chunk an app loads with `loadSet` when its places need it; DESIGN.md §12), from its `meta` (`PieceDef.meta`). *Params* are every one its drawing reads, with an enum's values (the default in bold), a number's range and default; *states* are the place states its art answers to; *variants* are its named looks (`PieceDef.variants`), each a set of params. A *solid* piece has solid lines on the floor that people walk round (`PieceDef.solid`, DESIGN.md §7). How they are drawn: `STYLE.md`. The gallery shows each one live with its params as controls (`#/kit/set/<id>`).",
    "",
  ];
  for (const [family, mod] of Object.entries(FAMILY_MODULES)) {
    lines.push(`## ${family}`, "", "| id | kind | what it is | params | states | variants | used in (samples) |", "|---|---|---|---|---|---|---|");
    for (const kind of ["set", "props"] as const) for (const [id, def] of Object.entries(mod[kind] as Record<string, PieceDef>).sort(([a], [b]) => a < b ? -1 : 1)) {
      const meta = def.meta, params = Object.entries(meta?.params ?? {}).sort(([a], [b]) => a < b ? -1 : 1);
      const variants = Object.keys(def.variants ?? {});
      lines.push(`| \`${id}\` | ${kind === "set" ? def.solid ? "piece, solid" : "piece" : "prop"} | ${cell(meta?.about ?? "") || "–"} | ${cell(params.map(([n, sp]) => paramCell(n, sp)).join("; ")) || "–"} | ${(meta?.states ?? []).join(", ") || "–"} | ${variants.map(v => `\`${v}\``).join(" ") || "–"} | ${(used[id] ?? []).join(", ") || "–"} |`);
    }
    lines.push("");
  }
  const credits = JSON.parse(readFileSync(CREDITS, "utf8")) as { id: string; family: string; by: string; contact: string; story?: string; date: string; licence: string; from: string }[];
  lines.push("## Credits", "", "Items drawn by the stories that first needed them and promoted into the kit (`drawing/promote.ts`, CONTRIBUTING.md *Contributing art*). Each author released their drawing under CC BY 4.0 ([LICENSE-ART](../../LICENSE-ART)) and said it is their own work; the credit is kept for as long as the item is. The drawings are `src/set/drawn/<family>/<id>.json`.", "");
  if (credits.length) {
    lines.push("| id | family | drawn by | contact | story | date | was |", "|---|---|---|---|---|---|---|");
    for (const c of credits) lines.push(`| \`${c.id}\` | ${c.family} | ${cell(c.by)} | ${cell(c.contact)} | ${cell(c.story ?? "–")} | ${c.date} | \`${c.from}\` |`);
  } else lines.push("None yet.");
  lines.push("");
  const planned = Object.entries(plan());
  lines.push("## Planned", "", "Still to draw (`set/plan.json`): new generators, and variants of built ones that a story's places already ask for; each leaves the plan when it is drawn.", "", "| id | family | step | kind | what it is | variants |", "|---|---|---|---|---|---|");
  for (const [id, p] of planned.sort(([, a], [, b]) => a.step < b.step ? -1 : a.step > b.step ? 1 : 0)) lines.push(`| \`${id}\`${p.built ? " (more variants)" : ""} | ${p.family} | ${p.step} | ${p.as === "both" ? "piece, prop" : p.as === "set" ? "piece" : "prop"} | ${cell(p.about)} | ${p.variants.map(v => `\`${v}\``).join(" ") || "–"} |`);
  lines.push("");
  return lines.join("\n");
}

/** Whether both written files are current. */
export function fresh(): boolean {
  try { return readFileSync(OUT, "utf8") === render() && readFileSync(MD, "utf8") === renderMd(); } catch { return false; }
}

if (import.meta.filename !== process.argv[1]) { /* imported (the kit's tests): nothing to run */ }
else if (process.argv.includes("--check")) {
  if (!fresh()) { console.error("src/set/families.gen.ts or SET.md is stale: run node packages/sahne-kit/set/build.ts"); process.exit(1); }
} else { writeFileSync(OUT, render()); writeFileSync(MD, renderMd()); }
