// Writes packages/sahne-kit/CATALOGUE.md: every part, face value, colour and pattern of the kit,
// drawn (from the kit itself) or still to come (catalogue/plan.json), each with what a learner may
// do with it (src/curation.ts). The kit and the curation file are the sources; this is their listing.
//
//   node packages/sahne-kit/catalogue/build.ts           write CATALOGUE.md
//   node packages/sahne-kit/catalogue/build.ts --check   fail when it is stale (the kit's tests run this)

import { readFileSync, writeFileSync } from "node:fs";
import { GARMENT_FIELDS } from "sahne";
import kit, { PATTERNS } from "../src/index.ts";
import { PARTS, COLORS, PATTERNS as CURATED_PATTERNS, FEATURES, type Avail, type Curated } from "../src/curation.ts";

const DIR = new URL(".", import.meta.url).pathname, OUT = DIR + "../CATALOGUE.md";

interface PlanPart { id: string; slot: string; en: string; tr: string; colors: number; patterns: string[]; builds: string[]; tags: string[]; status: string; cast: string[]; look: string }
interface Plan {
  parts: PlanPart[];
  features: { field: string; values: { value: string; en: string; tr: string; status: string; look: string }[] }[];
  patterns: { id: string; en: string; tr: string; status: string; look: string }[];
  palettes: Record<string, { id: string; hex: string; en: string; tr: string }[]>;
  deferred: { id: string; en: string; tr: string; why: string }[];
}

const AVAILS: Avail[] = ["open", "unlock", "cast", "hidden"];
const cell = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const row = (cells: unknown[]) => `| ${cells.map(cell).join(" | ")} |`;
const table = (head: string[], rows: unknown[][]) => rows.length ? [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n") : "_none_";
const avail = (c: Curated | undefined) => (!c ? "open" : c.avail === "unlock" ? `unlock \`${c.unlock}\`` : c.avail) + (c?.starter ? " · **starter**" : "");
const list = (a: readonly string[] | undefined) => a?.length ? a.join(", ") : "";

/** The catalogue as markdown, from the kit, the plan and the curation file. */
export function build(): string {
  const plan: Plan = JSON.parse(readFileSync(DIR + "plan.json", "utf8"));
  const drawn = Object.entries(kit.parts), planned = plan.parts.filter(p => !kit.parts[p.id]);
  const slots = GARMENT_FIELDS.map(g => g.slot);
  const out: string[] = [];
  out.push("# Sahne kit catalogue",
    "",
    "<!-- Generated by `node packages/sahne-kit/catalogue/build.ts` from the kit, `catalogue/plan.json` and `src/curation.ts`; do not edit. -->",
    "",
    "Every part, face value, colour and pattern of the first kit: the ones drawn, and the ones the plan still has to draw. *Availability* is what a learner may do with it (`src/curation.ts`, the one file to edit when curating):",
    "",
    "- **open**: offered to every learner.",
    "- **unlock**: offered but locked until the app reports the token.",
    "- **cast**: reserved for the story cast; refused in a learner's document.",
    "- **hidden**: not offered; a document that has it still draws it.",
    "- **starter** (beside any of them): in what a new learner is offered at first; a field with no starter entry offers everything.",
    "");

  // counts
  const byAvail = (ids: string[]) => AVAILS.map(a => ids.filter(id => (PARTS[id]?.avail ?? "open") === a).length);
  out.push("## Counts", "",
    table(["Slot", "Drawn", "Planned", ...AVAILS.map(a => `${a} (drawn + planned)`)],
      [...slots.map(s => {
        const d = drawn.filter(([, p]) => p.slot === s).map(([id]) => id), q = planned.filter(p => p.slot === s).map(p => p.id);
        return [s, d.length, q.length, ...byAvail([...d, ...q])];
      }).filter(r => (r[1] as number) + (r[2] as number) > 0),
      ["**all**", drawn.length, planned.length, ...byAvail([...drawn.map(([id]) => id), ...planned.map(p => p.id)])]]),
    "",
    `Face values: ${Object.entries(kit.features).filter(([f]) => f.startsWith("face.") || f === "facialHair").reduce((n, [, c]) => n + c.values.filter(Boolean).length, 0)} drawn. ` +
    `Patterns: ${Object.keys(PATTERNS).length} drawn, ${plan.patterns.filter(p => !PATTERNS[p.id]).length} planned. ` +
    `Colours: ${Object.values(kit.palettes).reduce((n, p) => n + Object.keys(p).length, 0)} palette entries (with the unions). ` +
    `Deferred: ${plan.deferred.length}.`,
    "");

  // parts, by slot
  out.push("## Parts", "");
  for (const s of slots) {
    const d = drawn.filter(([, p]) => p.slot === s), q = planned.filter(p => p.slot === s);
    if (!d.length && !q.length) continue;
    const field = GARMENT_FIELDS.find(g => g.slot === s)!.field;
    out.push(`### ${s} (\`${field}\`)`, "");
    if (d.length) out.push(table(["Id", "English", "Türkçe", "Colours", "Patterns", "Builds", "Availability", "Tags"],
      d.map(([id, p]) => [`\`${id}\``, p.names?.en ?? p.name ?? id, p.names?.tr ?? "", p.colors ?? 0, (p.patterns ?? []).length || "", list(p.builds) || "all", avail(PARTS[id]),
        list(p.tags?.filter(t => t !== "cast" && t !== "hidden"))])), "");
    if (q.length) out.push(`Planned, not drawn yet (${q.length}):`, "",
      table(["Id", "English", "Türkçe", "Availability", "Look"], q.map(p => [`\`${p.id}\``, p.en, p.tr, avail(PARTS[p.id]), p.look])), "");
  }

  // face
  out.push("## Face values", "");
  const planField = new Map(plan.features.map(f => [f.field, f]));
  for (const [field, c] of Object.entries(kit.features)) {
    if (!field.startsWith("face.") && field !== "facialHair") continue;
    const have = c.values.filter(Boolean) as string[], pf = planField.get(field);
    const todo = (pf?.values ?? []).filter(v => !have.includes(v.value) && v.status !== "retired");
    out.push(`### \`${field}\``, "",
      table(["Value", "English", "Türkçe", "Availability"], have.map(v => [`\`${v}\`${v === c.default ? " (default)" : ""}`, c.names?.[v]?.en ?? "", c.names?.[v]?.tr ?? "", avail(FEATURES[`${field}:${v}`])])), "");
    if (todo.length) out.push(`Planned: ${todo.map(v => `\`${v.value}\` (${v.en})`).join(", ")}.`, "");
  }

  // colours
  out.push("## Colours", "", "Skin is never locked. A colour not listed in `curation.ts` is open.", "");
  for (const name of ["skin", "hair", "eyes", "fabric", "metal", "lens"]) {
    const pal = (kit.palettes as Record<string, Record<string, string>>)[name];
    if (!pal) continue;
    const todo = (plan.palettes[name] ?? []).filter(c => !Object.hasOwn(pal, c.id));
    out.push(`### ${name} (${Object.keys(pal).length})`, "",
      table(["Id", "Hex", "English", "Türkçe", "Availability"], Object.entries(pal).map(([id, hex]) => [`\`${id}\``, `\`${hex}\``, kit.colorNames?.[id]?.en ?? "", kit.colorNames?.[id]?.tr ?? "", avail(COLORS[id])])), "");
    if (todo.length) out.push(`Planned: ${todo.map(c => `\`${c.id}\` ${c.en} \`${c.hex}\``).join(", ")}.`, "");
  }

  // patterns
  out.push("## Patterns", "",
    table(["Id", "English", "Türkçe", "Status", "Availability"], [
      ...Object.entries(PATTERNS).map(([id, p]) => [`\`${id}\``, p.names.en, p.names.tr, "drawn", avail(CURATED_PATTERNS[id])]),
      ...plan.patterns.filter(p => !PATTERNS[p.id]).map(p => [`\`${p.id}\``, p.en, p.tr, "planned", avail(CURATED_PATTERNS[p.id])]),
    ]), "");

  // later
  out.push("## Deferred", "", "Waiting for an engine feature or a consultation first.", "",
    table(["Id", "English", "Türkçe", "Why"], plan.deferred.map(x => [`\`${x.id}\``, x.en, x.tr, x.why])), "");
  return out.join("\n");
}

/** The problems, none when CATALOGUE.md is current. */
export function check(): string[] {
  let have = "";
  try { have = readFileSync(OUT, "utf8"); } catch { return ["CATALOGUE.md is missing: run node packages/sahne-kit/catalogue/build.ts"]; }
  return have === build() ? [] : ["CATALOGUE.md is stale: run node packages/sahne-kit/catalogue/build.ts"];
}

if (import.meta.filename !== process.argv[1]) { /* imported (the kit's tests): nothing to run */ }
else if (process.argv.includes("--check")) {
  const p = check();
  for (const m of p) console.error(m);
  process.exit(p.length ? 1 : 0);
} else {
  writeFileSync(OUT, build());
  console.log(`wrote ${OUT}`);
}
