export interface Item { family: string; doc: DrawingDoc }

/** Every promoted drawing in `drawn/<family>/<id>.json`, by family then id. */
export function readDrawn(dir = DRAWN_DIR): Item[] {
  if (!existsSync(dir)) return [];
  const out: Item[] = [];
  for (const d of readdirSync(dir, { withFileTypes: true }).filter(d => d.isDirectory()).sort((a, b) => a.name.localeCompare(b.name)))
    for (const f of readdirSync(join(dir, d.name)).filter(f => f.endsWith(".json")).sort()) out.push({ family: d.name, doc: JSON.parse(readFileSync(join(dir, d.name, f), "utf8")) });
  return out;
}

/** The families whose file takes drawn items: it imports `./drawn/<family>.gen.ts`. */
export function wiredFamilies(dir = SET_DIR): string[] {
  return readdirSync(dir).filter(f => f.endsWith(".ts")).map(f => f.slice(0, -3)).filter(f => readFileSync(join(dir, `${f}.ts`), "utf8").includes(`./drawn/${f}.gen.ts`)).sort();
}

const HEAD = "// Generated by packages/sahne-kit/drawing/promote.ts: do not edit.";
const strip = (d: DrawingDoc): DrawingDoc => { const { credit: _, ...rest } = d; return rest; };

/** A family's promoted drawings as a TS const (no credits: CREDITS.json carries them), import-free but for a type. */
export function genOf(family: string, docs: readonly DrawingDoc[]): string {
  return `${HEAD} The ${family} family's drawings promoted from stories (src/set/drawn/${family}/), which ${family}.ts runs through drawnFamily. Credits: CREDITS.json.\n\n`
    + `import type { DrawingDoc } from "../../drawing.ts";\n\nexport const DRAWN: DrawingDoc[] = [${docs.length ? `\n${docs.map(d => `  ${JSON.stringify(strip(d))}`).join(",\n")}\n` : ""}];\n`;
}

/** The ids stories used, now answered by the kit's `aliases`: x_… → the official id. */
export function aliasesOf(items: readonly Item[]): string {
  const rows = items.filter(i => i.doc.credit?.from).map(i => [i.doc.credit!.from, i.doc.id] as const).sort(([a], [b]) => (a < b ? -1 : 1));
  return `${HEAD} The content ids that promoted items replace, which \`kit.aliases\` carries (the engine's piece and prop lookup, familiesOf and lintPlace follow them): a story that still names its x_ copy keeps working.\n\n`
    + `export const DRAWN_ALIASES: Record<string, string> = {${rows.length ? `\n${rows.map(([a, b]) => `  ${a}: "${b}",`).join("\n")}\n` : ""}};\n`;
}

export interface Credited extends Credit { id: string; family: string; kind: "set" | "prop" | "both" }
/** Who drew what: every promoted item with its credit, by id. */
export const creditsOf = (items: readonly Item[]): Credited[] => items.map(i => ({ id: i.doc.id, family: i.family, kind: (i.doc.as === "set" ? "set" : i.doc.as === "prop" ? "prop" : "both") as Credited["kind"], ...i.doc.credit! })).sort((a, b) => (a.id < b.id ? -1 : 1));

/** Every file this script writes (apart from SET.md and families.gen.ts, which set/build.ts writes from them), with its text. */
export function generated(items: readonly Item[], wired: readonly string[]): Map<string, string> {
  const out = new Map<string, string>();
  const by = new Map<string, DrawingDoc[]>();
  for (const f of wired) by.set(f, []);
  for (const i of items) by.set(i.family, [...(by.get(i.family) ?? []), i.doc]);
  for (const [f, docs] of by) out.set(join(DRAWN_DIR, `${f}.gen.ts`), genOf(f, docs));
  out.set(join(DRAWN_DIR, "aliases.gen.ts"), aliasesOf(items));
  out.set(join(DRAWN_DIR, "CREDITS.json"), `${JSON.stringify(creditsOf(items), null, 2)}\n`);
  return out;
}

/** What is wrong with the folder and the files made from it, as lines ([] when current). Does not run set/build.ts. */
export function stale(): string[] {
  const items = readDrawn(), wired = wiredFamilies(), out: string[] = [];
  for (const i of items) {
    if (!wired.includes(i.family)) out.push(`src/set/drawn/${i.family}/ has drawings but ${i.family}.ts does not take drawn items (import DRAWN from "./drawn/${i.family}.gen.ts")`);
    if (!KIT_ID.test(i.doc.id)) out.push(`${i.family}/${i.doc.id}.json: ${JSON.stringify(i.doc.id)} is not a kit id (lowercase snake_case, never x_)`);
    if (!i.doc.credit) out.push(`${i.family}/${i.doc.id}.json has no credit with consent`);
    else for (const m of creditProblems(i.doc.credit)) out.push(`${i.family}/${i.doc.id}.json: ${m}`);
  }
  const froms = new Map<string, string>();
  for (const i of items) {
    const f = i.doc.credit?.from;
    if (!f) continue;
    if (froms.has(f)) out.push(`${f} is the old id of both ${froms.get(f)} and ${i.doc.id}: only one item can be its successor`);
    else froms.set(f, i.doc.id);
  }
  for (const f of readdirSync(DRAWN_DIR, { withFileTypes: true }).filter(d => d.isDirectory())) for (const j of readdirSync(join(DRAWN_DIR, f.name)))
    if (!items.some(i => i.family === f.name && `${i.doc.id}.json` === j)) out.push(`src/set/drawn/${f.name}/${j} is not named for its drawing's id`);
  const want = generated(items, wired);
  for (const [path, text] of want) if (!existsSync(path) || readFileSync(path, "utf8") !== text) out.push(`${relative(ROOT, path)} is stale`);
  for (const f of readdirSync(DRAWN_DIR).filter(f => f.endsWith(".gen.ts"))) if (!want.has(join(DRAWN_DIR, f))) out.push(`src/set/drawn/${f} belongs to no family that takes drawn items`);
  return out;
}

const node = (args: string[], cwd = ROOT) => spawnSync(process.execPath, args, { cwd, encoding: "utf8" });

/** Writes the generated files, then SET.md and families.gen.ts (set/build.ts, in a fresh process: it reads the files just written). */
export function regenerate(): void {
  const want = generated(readDrawn(), wiredFamilies());
  mkdirSync(DRAWN_DIR, { recursive: true });
  for (const f of readdirSync(DRAWN_DIR).filter(f => f.endsWith(".gen.ts"))) if (!want.has(join(DRAWN_DIR, f))) rmSync(join(DRAWN_DIR, f));
  for (const [path, text] of want) writeFileSync(path, text);
  const b = node([join(KIT, "set/build.ts")]);
  if (b.status !== 0) throw new Error(`set/build.ts failed:\n${b.stderr || b.stdout}`);
}

/** Everything this script generates is current, SET.md and families.gen.ts too: the lines that say what is not. */
export function check(): string[] {
  const out = stale();
  const b = node([join(KIT, "set/build.ts"), "--check"]);
  if (b.status !== 0) out.push("SET.md or families.gen.ts is stale: run node packages/sahne-kit/set/build.ts");
  return out;
}

