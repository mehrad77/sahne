#!/usr/bin/env node
// Promote: a drawing from a story's content root (kit/pieces/x_….json) becomes official Sahne art, with its author's credit.
// The one entry point, also the MCP tool `promote_kit_item` (sahne-backstage). The law is DRAWING.md *Promoting* and
// CONTRIBUTING.md *Contributing art*.
//
//   node packages/sahne-kit/drawing/promote.ts <content-root>/kit/pieces/x_cafe_chalkboard.json \
//     --id chalkboard --family bakery --by "Ada L." --contact github:ada --consent [--pr] [--dry] [--out promote-out]
//   node packages/sahne-kit/drawing/promote.ts --check      the generated files below are current
//   node packages/sahne-kit/drawing/promote.ts --regenerate  write them
//   node packages/sahne-kit/drawing/promote.ts --sheet butter_cookie,chalkboard [--out dir]   the review sheets of items already in the kit
//
// What it does, in order:
//   1 checks   `officialProblems` (sahne-kit/check) on the drawing under its new id with its credit, the schema, and the
//              family's size with the item in it (packages/sahne-gallery/size.mjs --family). Refuses without --consent.
//   2 writes   src/set/drawn/<family>/<id>.json, then regenerates what comes from the folder: src/set/drawn/<family>.gen.ts
//              (the family's drawings as a TS const), aliases.gen.ts (x_… → id, which `kit.aliases` carries and the engine's
//              piece and prop lookup, familiesOf and lintPlace follow) and CREDITS.json, and then runs set/build.ts for SET.md
//              (its Credits section) and families.gen.ts. These are the only files it writes.
//   3 sheets   promote-out/<id>.png (the item as the gallery sheet shows it) and <id>-neighbours.png (its family at one scale).
//   4 --pr     a branch art/<id> in a clone, committed as `feat(kit): <id>, drawn by <by>` with a Co-Authored-By for the author,
//              pushed to the user's fork (`gh repo fork` when they cannot write), and a pull request from promote-out/<id>.pr.md
//              with `gh pr create`. Without `gh`, promote-out/<id>.patch and <id>.pr.md, and what to do with them.
//
// Run outside a Sahne checkout (an app's own folder), or with --pr, it works in a temporary clone (SAHNE_REPO_URL, default
// https://github.com/mehrad77/sahne.git), so nobody needs a checkout and a checkout's working tree is never touched.
// --dry checks and draws the sheet and writes nothing.

