/** Reads the source drawing and puts it under its new id with the credit. Throws a message when it cannot. */
function promotedDoc(o: Options): DrawingDoc {
  const src = typeof o.source === "string" ? JSON.parse(readFileSync(o.source, "utf8")) as DrawingDoc : o.source;
  if (!src || typeof src !== "object" || typeof src.id !== "string") throw new Error("the source is not a drawing (an object with an id)");
  if (!/^x_[a-z0-9_]+$/.test(src.id)) throw new Error(`the source's id is ${JSON.stringify(src.id)}: only a content drawing (x_…) is promoted; a kit item is already official`);
  const { credit: _, id: __, ...rest } = src;
  return { id: o.id, ...rest, credit: creditOf(o, src.id) };
}

/** The family's chunk (gzip bytes) with these drawings in it, and its budget; null when esbuild is not there to measure. */
export function familySize(family: string, docs: readonly DrawingDoc[]): { gzip: number; budget: number } | null {
  const dir = mkdtempSync(join(realpathSync(tmpdir()), "sahne-size-")), gen = join(dir, `${family}.gen.ts`);
  try {
    writeFileSync(gen, genOf(family, docs).replace('"../../drawing.ts"', JSON.stringify(join(KIT, "src/drawing.ts"))));
    const r = node([join(ROOT, "packages/sahne-gallery/size.mjs"), "--json", "--family", family, "--gen", gen]);
    const row = r.stdout ? (JSON.parse(r.stdout.trim().split("\n").pop()!) as { gzip: number; budget: number }[])[0] : undefined;
    return row?.budget ? { gzip: row.gzip, budget: row.budget } : null;
  } catch { return null; } finally { rmSync(dir, { recursive: true, force: true }); }
}

/** The review sheets of a drawing under its kit id: the item as the kit sheet shows it, and its family at one scale. Returns their paths. */
export async function drawSheets(doc: DrawingDoc, family: string, out: string): Promise<string[]> {
  const [{ drawnFamily }, { default: full }, { FAMILY_MODULES }, { kitSheetSvg, cellSheetSvg, SMALL_CM }, { rng, groupBounds }, { renderPng }] = await Promise.all([
    import("../src/drawing.ts"), import("../src/full.ts"), import("../src/set/all.ts"), import("../src/set-svg.ts"), import("sahne"), import("../../sahne-backstage/server/render.ts"),
  ]);
  const images: string[] = [];
  const mine = drawnFamily([doc]), kit = { ...full, set: { ...full.set, ...mine.set }, props: { ...full.props, ...mine.props } };
  const kind = doc.as === "set" ? "set" as const : "props" as const, def = (kind === "set" ? mine.set : mine.props)[doc.id];
  mkdirSync(out, { recursive: true });
  const sheet = join(out, `${doc.id}.png`), near = join(out, `${doc.id}-neighbours.png`);
  writeFileSync(sheet, renderPng(kitSheetSvg(kit, [{ id: doc.id, def, kind }]), { background: "#E8E1D4" }));
  images.push(sheet);
  // its neighbours: the family's items sharing the most tags, one default look each, all at one scale: the scene's (beside the
  // adult) when any is large, else one box of cm round all of them, so a cup and a salami are told apart by size
  const mod = FAMILY_MODULES[family];
  if (mod) {
    const tags = new Set(doc.tags ?? []), seen = new Set<string>();
    const pool = (["props", "set"] as const).flatMap(k => Object.entries(mod[k]).map(([id, d]) => ({ id, def: d, kind: k, hit: (d.meta?.tags ?? []).filter(t => tags.has(t)).length })));
    const friends = pool.filter(p => p.id !== doc.id && !seen.has(`${p.kind}:${p.id}`) && seen.add(`${p.kind}:${p.id}`)).sort((a, b) => b.hit - a.hit || a.id.localeCompare(b.id)).slice(0, 11);
    const group = [{ id: doc.id, def, kind }, ...friends];
    const box = group.map(g => g.def.draw({}, rng(`${g.id}/a`), kit).flats.map(f => groupBounds(f.group))).flat();
    const w = Math.max(...box.map(b => Math.max(-b[0], b[2]))), h = Math.max(...box.map(b => -b[1]));
    const small = Math.max(w * 2, h) <= SMALL_CM, pad = (v: number) => Math.ceil(v * 1.1);
    const cells = group.map((g, i) => ({ item: { id: g.id, def: g.def, kind: g.kind }, label: "default", params: {}, num: i + 1, ...(small ? { focus: [-pad(w), -pad(h), pad(w), 1] as [number, number, number, number] } : {}) }));
    writeFileSync(near, renderPng(cellSheetSvg(kit, cells, { zoom: small ? "auto" : "scene", columns: 6 }), { background: "#E8E1D4" }));
    images.push(near);
  }
  return images;
}

/** Checks the drawing and draws its sheets; writes nothing to the kit. */
async function inspect(o: Options, doc: DrawingDoc): Promise<{ problems: Problem[]; images: string[]; notes: string[] }> {
  const [{ officialProblems }, { compileDrawing }, { default: full }, { FAMILIES }, groups, set] = await Promise.all([
    import("../src/check.ts"), import("../src/drawing.ts"), import("../src/full.ts"), import("../src/set/index.ts"),
    import("../../sahne-backstage/src/model/kitgroups.ts"), import("../../sahne-story/check/schema.ts"),
  ]);
  const notes: string[] = [], problems: Problem[] = [];
  // the schema of the content drawing: the promoted copy is checked as the x_ copy it was
  for (const s of set.validateDoc("kit_piece", { ...strip(doc), id: doc.credit!.from })) problems.push({ level: "error", rule: "official", id: doc.id, msg: `schema ${s.path} ${s.message}` });
  const tagsOf = (shelves: readonly { tags?: readonly string[] }[]) => new Set(shelves.flatMap(s => s.tags ?? []));
  const items = readDrawn().filter(i => i.doc.id !== doc.id), size = Object.hasOwn(FAMILIES, o.family) ? familySize(o.family, [...items.filter(i => i.family === o.family).map(i => i.doc), doc]) : null;
  if (!size) notes.push("note: the family's size was not measured (esbuild is not installed here); pnpm check measures it");
  problems.push(...officialProblems(doc, {
    kit: full, family: o.family, families: Object.keys(FAMILIES), wired: wiredFamilies().includes(o.family),
    shelfTags: { props: tagsOf(groups.PROP_SHELVES), set: tagsOf(groups.SET_SHELVES) }, ...(size ? { size } : {}),
  }));
  const images = compileDrawing(doc, true).problems.length ? [] : await drawSheets(doc, o.family, o.out ?? join(process.cwd(), "promote-out"));
  return { problems, images, notes };
}

const errors = (ps: readonly Problem[]) => ps.filter(p => p.level === "error");
const line = (p: Problem) => `${p.level === "warn" ? "warning" : "error"}: ${p.msg}`;

/** The pull request's text: the template's sections, filled (.github/PULL_REQUEST_TEMPLATE/art.md). */
export function prText(doc: DrawingDoc, family: string): string {
  const c = doc.credit!, at = (v: string) => v.replace(/@/g, "@\u200b"); // GitHub pings an @name
  const by = at(c.by), contact = at(c.contact), story = c.story ? at(c.story) : undefined;
  return [
    `## ${doc.id}: ${doc.about}`, "",
    "### The sheet", "",
    `CI renders the review sheet and the family comparison for this item and links them in a comment below. Locally: promote-out/${doc.id}.png and promote-out/${doc.id}-neighbours.png.`, "",
    "### What it is", "",
    `${doc.about} A ${doc.as === "both" ? "set piece and prop" : doc.as === "set" ? "set piece" : "prop"} of the \`${family}\` family, tags: ${(doc.tags ?? []).join(", ") || "none"}.`, "",
    "### Where it was used", "",
    `${story ? `Story: ${story}. ` : ""}Its content id there was \`${c.from}\`; the kit's \`aliases\` now answer to it, so a story that still names it keeps working.`, "",
    "### Credit and consent", "",
    `- Drawn by ${by} (${contact}), ${c.date}.`,
    c.consent === "project" ? "- [x] The project's own art, drawn by the owner's kit agents (consent: project): the owner's merge is the consent." : "- [x] The author releases this drawing under CC BY 4.0 (LICENSE-ART) and says it is their own work, not traced or copied.",
    `- It is recorded in src/set/drawn/${family}/${doc.id}.json (\`credit\`) and credited in SET.md and CREDITS.json.`, "",
    "### Reviewer's checklist", "",
    "- [ ] Cut paper: no outlines, no drawn grain; details printed on the paper are `flat`.",
    "- [ ] Light from the upper left; colours from the kit's or a tone of one (STYLE.md *Paper*).",
    "- [ ] Puppet scale: real centimetres, readable beside the 170 cm adult or on the scale bar.",
    "- [ ] Words are `text` with a `lang`, never shapes.",
    "- [ ] Nothing traced: no landmark, logo or brand copied.",
    "- [ ] The id is the one it should have for good (ids are permanent).",
    "- [ ] `pnpm check` is green; the family stays within its 40 KB.", "",
  ].join("\n");
}

