/** The unlock tokens of one kind of id, `{ id: token }`, for the ids that have one. */
export function unlocksOf(kind: "color" | "pattern" | "part"): Record<string, string> {
  const t = kind === "color" ? COLORS : kind === "pattern" ? PATTERNS : PARTS;
  return Object.fromEntries(Object.entries(t).flatMap(([id, c]) => (c.avail === "unlock" && c.unlock ? [[id, c.unlock]] : [])));
}

/** A part's availability (`open` for an id this file does not list: the kit tests make sure there is none). */
export const availOf = (id: string): Avail => (Object.hasOwn(PARTS, id) ? PARTS[id].avail : "open");
