// What a learner may pick (DESIGN.md §10): the one place the owner curates the kit. Every part id the
// kit draws or the plan (catalogue/plan.json) still has to draw has one entry here, and so has every
// pattern; colours are listed only when they are not open. index.ts applies this file to the parts
// (`PartDef.unlock` and the `cast` / `hidden` tags), palette.ts to `kit.paletteUnlocks` and
// patterns.ts to `PatternDef.unlock`; the art files never set `unlock`, `cast` or `hidden`
// themselves. Curating later is editing this file only, then `node packages/sahne-kit/catalogue/build.ts`
// (CATALOGUE.md lists it) and the kit's tests.
//
//   open    offered to every learner
//   unlock  offered, but locked until the app reports `unlock` (`bundle:<name>`, `story:<episode>`, …)
//   cast    never offered, and refused in a learner's document: reserved for the cast (tag `cast`)
//   hidden  never offered, but a document that has it still draws it: retired or not ready (tag `hidden`)
//
// Rules: never lock a faith, body-trait, heritage-of-identity or accessibility item (a headscarf, a
// hearing aid, a cane); skin is never locked. A friend's document may use anything: only the builder
// looks here. The seed (2026-10-10) is the kit review's suggested availability; its
// bundle names are placeholders for the owner to regroup. A face value has no lock in the builder
// yet, so `FEATURES` is recorded but not applied.

export type Avail = "open" | "unlock" | "cast" | "hidden";
export interface Curated {
  avail: Avail;
  /**
   * In the starter set: what a new learner is offered at first, a few per field, so the builder does
   * not overwhelm (the rest waits behind the field's "More"). A field with no starter entry offers
   * everything. The cast's designer is never limited. See `starterOffer` in index.ts.
   */
  starter?: true;
  /** The token the app reports when a learner has it (only with `unlock`). */
  unlock?: string;
  /** Why, in a few words, or which cast member wears it. */
  note?: string;
}

